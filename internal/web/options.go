// swatchOption is a style choice with an inline SVG preview.
type swatchOption struct {
	Value, Label string
	SVG          template.HTML
}

// designOptions are the choices offered in the Design step; built once.
type designOptions struct {
	Modules, EyeOuters, EyeInners, Icons []swatchOption
	Frames, Fonts, Pages                 []render.Option
	Formats                              []render.Option
	MaxFrameText                         int
}

func newDesignOptions() *designOptions {
	// Swatches are generated by our renderer from fixed shapes, not user input.
	swatch := func(opts []render.Option, svg func(string) string) []swatchOption {
		out := make([]swatchOption, len(opts))
		for i, o := range opts {
			out[i] = swatchOption{o.Value, o.Label, template.HTML(svg(o.Value))}
		}
		return out
	}
	return &designOptions{
		Modules:   swatch(render.ModuleShapes, render.ModuleSwatchSVG),
		EyeOuters: swatch(render.EyeOuterShapes, func(v string) string { return render.EyeSwatchSVG(v, "square") }),
		EyeInners: swatch(render.EyeInnerShapes, func(v string) string { return render.EyeSwatchSVG("square", v) }),
		Icons:     swatch(render.Icons(), render.IconSwatchSVG),
		Frames:    render.Frames,
		Fonts:     render.Fonts,
		Pages:     render.Pages,
		Formats: []render.Option{
			{Value: "png", Label: "PNG"}, {Value: "jpeg", Label: "JPEG"}, {Value: "svg", Label: "SVG (vector)"},
			{Value: "pdf", Label: "PDF (vector, print)"}, {Value: "eps", Label: "EPS (vector, print shops)"},
		},
		MaxFrameText: render.MaxFrameText,
	}
}

// assetLoader resolves uploaded logos for rendering, caching decoded images.
func (s *Server) assetLoader(ctx context.Context) generate.AssetLoader {
	return func(id string) (image.Image, error) {
		if img, ok := s.logoCache.Load(id); ok {
			return img.(image.Image), nil
		}
		a, err := s.store.GetAsset(ctx, id)
		if errors.Is(err, store.ErrNotFound) {
			return nil, errors.New("the uploaded logo no longer exists; upload it again")
		} else if err != nil {
			return nil, err
		}
		img, err := png.Decode(bytes.NewReader(a.Data))
		if err != nil {
			return nil, fmt.Errorf("stored logo is unreadable: %w", err)
		}
		s.logoCache.Store(id, img)
		return img, nil
	}
}

// fontLoader resolves uploaded frame fonts, caching parsed fonts.
func (s *Server) fontLoader(ctx context.Context) generate.FontLoader {
	return func(id string) (*render.Font, error) {
		if f, ok := s.fontCache.Load(id); ok {
			return f.(*render.Font), nil
		}
		a, err := s.store.GetAsset(ctx, id)
		if errors.Is(err, store.ErrNotFound) {
			return nil, errors.New("the uploaded font no longer exists; upload it again")
		} else if err != nil {
			return nil, err
		}
		f, err := render.ParseFont(a.Data)
		if err != nil {
			return nil, err
		}
		s.fontCache.Store(id, f)
		return f, nil
	}
}
